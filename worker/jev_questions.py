"""System One question definitions for the Jev client.

System One request bodies are ``{state, model, questions}``. Every question is
one of three primitives and is validated here *before* any HTTP call, so an
unsupported shape can never reach the network.

Question IDs are opaque and generated by code. They carry no business meaning
(the model does not reason about them), so candidate labels, message text and
rubrics must live in ``state`` / ``instructions`` / ``criteria``.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any, Mapping, Sequence

from worker.jev_config import (
    MAX_CHOICE_OPTIONS,
    MAX_QUESTIONS_PER_REQUEST,
    MAX_SCORE_LEVELS,
    MIN_SCORE_LEVELS,
)

NO_MATCH_OPTION = "none"

_TYPE_NOUL = "noul"
_TYPE_CHOICE = "choice"
_TYPE_SCORE = "score"

# Keys allowed inside a Noul rubric.
_NOUL_CRITERIA_KEYS = ("true", "false")


class JevQuestionError(ValueError):
    """A question definition cannot be encoded in the System One contract."""


def _is_json_value(value: Any) -> bool:
    try:
        json.dumps(value, ensure_ascii=False)
    except (TypeError, ValueError):
        return False
    return True


def _require_instructions(value: Any, label: str) -> Any:
    if value is None or (isinstance(value, str) and not value.strip()):
        raise JevQuestionError(f"{label} requires non-empty instructions")
    if not _is_json_value(value):
        raise JevQuestionError(f"{label} instructions must be JSON-compatible")
    return value


@dataclass(frozen=True)
class NoulQuestion:
    """A yes/no question returning a single probability of "yes"."""

    instructions: Any
    criteria: Mapping[str, Any] = field(default_factory=dict)

    def payload(self, label: str) -> dict[str, Any]:
        instructions = _require_instructions(self.instructions, label)
        payload: dict[str, Any] = {"type": _TYPE_NOUL, "instructions": instructions}
        if self.criteria:
            unknown = [key for key in self.criteria if key not in _NOUL_CRITERIA_KEYS]
            if unknown:
                raise JevQuestionError(
                    f"{label} noul criteria only accepts 'true'/'false', got {sorted(unknown)}"
                )
            if not _is_json_value(dict(self.criteria)):
                raise JevQuestionError(f"{label} noul criteria must be JSON-compatible")
            payload["criteria"] = dict(self.criteria)
        return payload


@dataclass(frozen=True)
class ChoiceQuestion:
    """Pick one label from a bounded option map."""

    instructions: Any
    options: Mapping[str, Any]

    def payload(self, label: str) -> dict[str, Any]:
        instructions = _require_instructions(self.instructions, label)
        if not isinstance(self.options, Mapping) or not self.options:
            raise JevQuestionError(f"{label} choice requires a non-empty criteria map")
        if len(self.options) > MAX_CHOICE_OPTIONS:
            raise JevQuestionError(
                f"{label} choice has {len(self.options)} options; the limit is {MAX_CHOICE_OPTIONS}"
            )
        criteria: dict[str, Any] = {}
        for key, value in self.options.items():
            option_id = str(key)
            if not option_id.strip():
                raise JevQuestionError(f"{label} choice option IDs must be non-empty")
            if option_id in criteria:
                raise JevQuestionError(f"{label} choice option IDs must be unique: {option_id}")
            if not _is_json_value(value):
                raise JevQuestionError(f"{label} choice option '{option_id}' must be JSON-compatible")
            criteria[option_id] = value
        return {"type": _TYPE_CHOICE, "instructions": instructions, "criteria": criteria}


@dataclass(frozen=True)
class ScoreQuestion:
    """Rate the state on an ordered rubric, lowest level first."""

    instructions: Any
    levels: Sequence[Any]

    def payload(self, label: str) -> dict[str, Any]:
        instructions = _require_instructions(self.instructions, label)
        if isinstance(self.levels, (str, bytes)) or not isinstance(self.levels, Sequence):
            raise JevQuestionError(f"{label} score requires an ordered criteria array")
        levels = list(self.levels)
        if not MIN_SCORE_LEVELS <= len(levels) <= MAX_SCORE_LEVELS:
            raise JevQuestionError(
                f"{label} score needs {MIN_SCORE_LEVELS}-{MAX_SCORE_LEVELS} levels, got {len(levels)}"
            )
        if not _is_json_value(levels):
            raise JevQuestionError(f"{label} score levels must be JSON-compatible")
        return {"type": _TYPE_SCORE, "instructions": instructions, "criteria": levels}


JevQuestion = NoulQuestion | ChoiceQuestion | ScoreQuestion


def question_type(question: JevQuestion) -> str:
    if isinstance(question, NoulQuestion):
        return _TYPE_NOUL
    if isinstance(question, ChoiceQuestion):
        return _TYPE_CHOICE
    if isinstance(question, ScoreQuestion):
        return _TYPE_SCORE
    raise JevQuestionError(f"unsupported question type: {type(question).__name__}")


@dataclass(frozen=True)
class QuestionSet:
    """A validated, non-empty question map plus its expected answer types."""

    questions: Mapping[str, dict[str, Any]]
    types: Mapping[str, str]

    def ids(self) -> tuple[str, ...]:
        return tuple(self.questions.keys())

    def payload(self) -> dict[str, dict[str, Any]]:
        return {key: dict(value) for key, value in self.questions.items()}

    def longest_instructions_chars(self) -> int:
        longest = 0
        for question in self.questions.values():
            encoded = json.dumps(
                {"instructions": question.get("instructions"), "criteria": question.get("criteria")},
                ensure_ascii=False,
            )
            longest = max(longest, len(encoded))
        return longest


def build_question_set(entries: Mapping[str, JevQuestion] | Sequence[tuple[str, JevQuestion]]) -> QuestionSet:
    """Validate ``entries`` and freeze them into a :class:`QuestionSet`.

    Accepts either an ordered mapping or a sequence of ``(question_id, question)``
    pairs so callers can build the opaque ``q0..qN`` ids themselves.
    """
    items = list(entries.items()) if isinstance(entries, Mapping) else list(entries)
    if not items:
        raise JevQuestionError("a Jev request requires at least one question")
    if len(items) > MAX_QUESTIONS_PER_REQUEST:
        raise JevQuestionError(
            f"a Jev request allows at most {MAX_QUESTIONS_PER_REQUEST} questions, got {len(items)}"
        )
    questions: dict[str, dict[str, Any]] = {}
    types: dict[str, str] = {}
    for raw_id, question in items:
        question_id = str(raw_id)
        if not question_id.strip():
            raise JevQuestionError("question IDs must be non-empty")
        if question_id in questions:
            raise JevQuestionError(f"duplicate question ID: {question_id}")
        questions[question_id] = question.payload(question_id)
        types[question_id] = question_type(question)
    return QuestionSet(questions=questions, types=types)


def opaque_ids(count: int, *, prefix: str = "q") -> list[str]:
    """Stable, content-free question IDs safe to write into the audit trail."""
    if count < 1:
        raise JevQuestionError("at least one opaque ID is required")
    return [f"{prefix}{index}" for index in range(count)]


def noul_bool(question_id: str, instructions: Any, *, true_hint: str = "", false_hint: str = "") -> tuple[str, NoulQuestion]:
    """Convenience builder for the common yes/no grading question."""
    criteria: dict[str, Any] = {}
    if true_hint:
        criteria["true"] = true_hint
    if false_hint:
        criteria["false"] = false_hint
    return question_id, NoulQuestion(instructions=instructions, criteria=criteria)
